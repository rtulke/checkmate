// Command mscp-import converts the rules of the macOS Security Compliance
// Project (https://github.com/usnistgov/macos_security, CC BY 4.0) that map
// to the CIS Apple macOS benchmark into a checkmate policy.
//
//	go run ./tools/mscp-import -src <checkout of a release branch> -macos 15 -out cis/macos15.yml
//
// mSCP rule titles are used as check names; the CIS recommendation number,
// its level and the NIST/DISA mappings are kept as tags and descriptions.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"
)

type rule struct {
	ID         string         `yaml:"id"`
	Title      string         `yaml:"title"`
	Check      string         `yaml:"check"`
	Result     any            `yaml:"result"`
	ODV        map[string]any `yaml:"odv"`
	Tags       []string       `yaml:"tags"`
	Severity   string         `yaml:"severity"`
	References struct {
		NIST []string `yaml:"800-53r5"`
		STIG []string `yaml:"disa_stig"`
		CIS  struct {
			Benchmark []string `yaml:"benchmark"`
			Controls  []any    `yaml:"controls v8"`
		} `yaml:"cis"`
	} `yaml:"references"`
}

// frameworkTags maps mSCP baseline tags to checkmate tags.
var frameworkTags = map[string]string{
	"800-53r5_low":      "nist-800-53r5-low",
	"800-53r5_moderate": "nist-800-53r5-moderate",
	"800-53r5_high":     "nist-800-53r5-high",
	"800-171":           "nist-800-171",
	"stig":              "disa-stig",
	"cmmc_lvl1":         "cmmc-level-1",
	"cmmc_lvl2":         "cmmc-level-2",
}

var names = map[string]string{"14": "Sonoma", "15": "Sequoia", "26": "Tahoe"}

func main() {
	src := flag.String("src", "", "checkout of a macos_security release branch")
	version := flag.String("macos", "", "macOS major version: 14, 15 or 26")
	out := flag.String("out", "", "output policy file")
	flag.Parse()
	if *src == "" || *out == "" || names[*version] == "" {
		fmt.Fprintln(os.Stderr, "usage: mscp-import -src DIR -macos 14|15|26 -out FILE")
		os.Exit(2)
	}
	n, skipped, err := convert(*src, *version, *out)
	if err != nil {
		fmt.Fprintln(os.Stderr, "mscp-import:", err)
		os.Exit(1)
	}
	fmt.Fprintf(os.Stderr, "macos%s: %d checks, %d CIS rules skipped (no automated check)\n", *version, n, skipped)
}

func convert(src, version, out string) (int, int, error) {
	files, err := filepath.Glob(filepath.Join(src, "rules", "*", "*.yaml"))
	if err != nil {
		return 0, 0, err
	}
	sort.Strings(files)
	mscpVersion := readVersion(src)

	var b bytes.Buffer
	fmt.Fprintf(&b, "# Generated by tools/mscp-import from usnistgov/macos_security (%s branch, CC BY 4.0).\n", strings.ToLower(names[version]))
	fmt.Fprintf(&b, "# Do not edit by hand; regenerate with `make cis-import`. See cis/NOTICE.\n")
	fmt.Fprintf(&b, "name: CIS Apple macOS %s %s\n", version, names[version])
	fmt.Fprintf(&b, "version: %s\n", jsonString(mscpVersion))
	fmt.Fprintf(&b, "description: >\n")
	fmt.Fprintf(&b, "  Checks for the recommendations of the CIS Apple macOS %s benchmark, taken\n", version)
	fmt.Fprintf(&b, "  from the rules of the macOS Security Compliance Project (mSCP). Many rules\n")
	fmt.Fprintf(&b, "  verify settings delivered by configuration profiles (MDM), as mSCP does.\n")
	fmt.Fprintf(&b, "  The checks need root, like mSCP itself: run with sudo. Select levels\n")
	fmt.Fprintf(&b, "  with `--tags cis-level-1` or `--tags cis-level-2`.\n\n")
	fmt.Fprintf(&b, "defaults:\n  when:\n    - %s\n    - facts.is_root\n  shell: zsh\n  timeout: 60s\n\nchecks:\n",
		jsonString(fmt.Sprintf(`facts.distro == "macos" and facts.version_major == %s`, version)))

	count, skipped := 0, 0
	type entry struct {
		key  string
		text string
	}
	var entries []entry
	for _, f := range files {
		data, err := os.ReadFile(f)
		if err != nil {
			return 0, 0, err
		}
		var r rule
		if err := yaml.Unmarshal(data, &r); err != nil {
			return 0, 0, fmt.Errorf("%s: %w", f, err)
		}
		level := cisLevel(r.Tags)
		if level == 0 {
			continue
		}
		if !automated(r) {
			skipped++
			continue
		}
		cisID := ""
		for _, ref := range r.References.CIS.Benchmark {
			cisID = strings.Fields(ref)[0]
			break
		}
		odv := odvValue(r.ODV, level)
		check := strings.TrimRight(strings.ReplaceAll(r.Check, "$ODV", odv), "\n")
		// mSCP runs every check inside a script that defines CURRENT_USER
		// first; a checkmate check runs alone, so it defines it itself
		// (same command as mSCP's generate_guidance.py).
		if strings.Contains(check, "CURRENT_USER") && !strings.Contains(check, "CURRENT_USER=") {
			check = currentUserLine + "\n" + check
		}
		if err := zshSyntax(check); err != nil {
			fmt.Fprintf(os.Stderr, "  skipped %s: invalid shell syntax: %v\n", r.ID, err)
			skipped++
			continue
		}
		result, _ := r.Result.(map[string]any)
		expect, ok := expectation(result, odv)
		if !ok {
			skipped++
			continue
		}
		var e bytes.Buffer
		id := "CIS-MACOS" + version + "-" + cisID + "-" + r.ID
		fmt.Fprintf(&e, "  - id: %s\n", jsonString(id))
		fmt.Fprintf(&e, "    name: %s\n", jsonString(strings.TrimSpace(strings.ReplaceAll(r.Title, "$ODV", odv))))
		fmt.Fprintf(&e, "    description: %s\n", jsonString(description(version, cisID, level, r)))
		fmt.Fprintf(&e, "    tags: [%s]\n", strings.Join(tags(version, cisID, level, r.Tags), ", "))
		fmt.Fprintf(&e, "    severity: %s\n", severity(r.Severity, level))
		e.WriteString("    run: |\n")
		for _, line := range strings.Split(protect(check), "\n") {
			e.WriteString("      " + line + "\n")
		}
		e.WriteString("    allow_rc: any\n")
		fmt.Fprintf(&e, "    expect: %s\n", expect)
		fmt.Fprintf(&e, "    reference: %s\n", jsonString("https://github.com/usnistgov/macos_security/blob/"+strings.ToLower(names[version])+"/rules/"+filepath.Base(filepath.Dir(f))+"/"+filepath.Base(f)))
		entries = append(entries, entry{key: cisID + "/" + r.ID, text: e.String()})
		count++
	}
	sort.Slice(entries, func(i, j int) bool { return naturalLess(entries[i].key, entries[j].key) })
	for _, e := range entries {
		b.WriteString(e.text)
	}
	if err := os.MkdirAll(filepath.Dir(out), 0o755); err != nil {
		return 0, 0, err
	}
	return count, skipped, os.WriteFile(out, b.Bytes(), 0o644)
}

func cisLevel(tags []string) int {
	level := 0
	for _, t := range tags {
		switch strings.TrimSpace(t) {
		case "cis_lvl1":
			return 1
		case "cis_lvl2":
			level = 2
		}
	}
	return level
}

// automated reports whether a rule has a check with a defined result.
func automated(r rule) bool {
	for _, t := range r.Tags {
		switch strings.TrimSpace(t) {
		case "inherent", "permanent", "n_a", "manual":
			return false
		}
	}
	check := strings.TrimSpace(r.Check)
	result, _ := r.Result.(map[string]any)
	if check == "" || strings.Contains(strings.ToLower(check), "not applicable") || len(result) == 0 {
		return false
	}
	return true
}

// currentUserLine is how mSCP determines the user whose settings are checked.
const currentUserLine = `CURRENT_USER=$(/usr/bin/defaults read /Library/Preferences/com.apple.loginwindow lastUserName)`

func odvValue(odv map[string]any, level int) string {
	if odv == nil {
		return ""
	}
	for _, k := range []string{fmt.Sprintf("cis_lvl%d", level), "cis_lvl1", "cis_lvl2", "recommended"} {
		if v, ok := odv[k]; ok {
			return fmt.Sprint(v)
		}
	}
	return ""
}

func expectation(result map[string]any, odv string) (string, bool) {
	for kind, v := range result {
		value := strings.ReplaceAll(fmt.Sprint(v), "$ODV", odv)
		switch kind {
		case "integer":
			if _, err := strconv.Atoi(value); err != nil {
				return "", false
			}
			return jsonString("== " + value), true
		case "string":
			return jsonString("== " + value), true
		case "boolean":
			if value == "true" || value == "1" {
				return jsonString("in [true, 1]"), true
			}
			return jsonString("in [false, 0]"), true
		}
	}
	return "", false
}

func tags(version, cisID string, level int, mscpTags []string) []string {
	t := []string{"cis", "cis-macos" + version}
	if section := strings.SplitN(cisID, ".", 2)[0]; section != "" {
		t = append(t, "cis-section-"+section)
	}
	if level == 1 {
		t = append(t, "cis-level-1")
	}
	t = append(t, "cis-level-2")
	seen := map[string]bool{}
	for _, mt := range mscpTags {
		if ft, ok := frameworkTags[strings.TrimSpace(mt)]; ok && !seen[ft] {
			t = append(t, ft)
			seen[ft] = true
		}
	}
	return t
}

func severity(s string, level int) string {
	switch strings.ToLower(s) {
	case "low", "medium", "high":
		return strings.ToLower(s)
	}
	if level == 1 {
		return "medium"
	}
	return "low"
}

func description(version, cisID string, level int, r rule) string {
	parts := []string{fmt.Sprintf("CIS Apple macOS %s benchmark recommendation %s (level %d); mSCP rule %s", version, cisID, level, r.ID)}
	if len(r.References.NIST) > 0 {
		parts = append(parts, "NIST SP 800-53 Rev. 5: "+strings.Join(r.References.NIST, ", "))
	}
	if len(r.References.STIG) > 0 {
		parts = append(parts, "DISA STIG: "+strings.Join(r.References.STIG, ", "))
	}
	return strings.Join(parts, ". ") + "."
}

func readVersion(src string) string {
	data, err := os.ReadFile(filepath.Join(src, "VERSION.yaml"))
	if err != nil {
		return "unknown"
	}
	var v map[string]any
	if yaml.Unmarshal(data, &v) != nil {
		return "unknown"
	}
	for _, k := range []string{"version", "os"} {
		if s, ok := v[k]; ok {
			return fmt.Sprint(s)
		}
	}
	return "unknown"
}

// zshSyntax checks a command with `zsh -n` (falls back to bash).
func zshSyntax(cmd string) error {
	shell := "zsh"
	if _, err := exec.LookPath("zsh"); err != nil {
		shell = "bash"
	}
	out, err := exec.Command(shell, "-n", "-c", cmd).CombinedOutput()
	if err != nil {
		return fmt.Errorf("%s", strings.TrimSpace(string(out)))
	}
	return nil
}

func protect(s string) string {
	if strings.Contains(s, "{{") || strings.Contains(s, "{%") {
		return "{% raw %}" + s + "{% endraw %}"
	}
	return s
}

func jsonString(s string) string {
	data, _ := json.Marshal(s)
	return string(data)
}

var naturalSplit = regexp.MustCompile(`\d+|\D+`)

func naturalLess(a, b string) bool {
	ra, rb := naturalSplit.FindAllString(a, -1), naturalSplit.FindAllString(b, -1)
	for i := 0; i < len(ra) && i < len(rb); i++ {
		if ra[i] == rb[i] {
			continue
		}
		na, ea := strconv.Atoi(ra[i])
		nb, eb := strconv.Atoi(rb[i])
		if ea == nil && eb == nil {
			return na < nb
		}
		return ra[i] < rb[i]
	}
	return len(ra) < len(rb)
}
